#include<stdio.h>
int main() {

    const float PI = 3.14;
    int age = 21;
    char grade = 'A';
    float salary = 45000.50;

    printf("Integer (Age): %d\n", age);
    printf("Character (Grade): %c\n", grade);
    printf("Float (Salary): %.2f\n", salary);
    printf("Constant (PI): %.2f\n", PI);
}
